export function getSubsystemIcon(id, size = 16) {
  switch (id) {
    case 'general':
      return <IconGlobe size={size} />
    case 'ml':
    case 'locomotion':
      return <IconRover size={size} />
    case 'electrical':
    case 'telemetry':
      return <IconTelemetry size={size} />
    case 'cams_comms':
    case 'rado':
      return <IconBroadcast size={size} />
    case 'arm_rado':
    case 'arm':
      return <IconArm size={size} />
    case 'core':
    default:
      return <IconCore size={size} />
  }
}
